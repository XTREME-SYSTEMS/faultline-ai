// Epoxy Garage Floors Near You — Service Worker
// Simple cache-first strategy for app shell offline support

const CACHE_NAME = 'epoxy-funnel-v1';
const APP_SHELL = [
  '/epoxy-estimate',
  '/epoxy-colors',
  '/epoxy-manifest.json',
  '/epoxy-icon.svg'
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(APP_SHELL)).catch(() => {})
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  if (event.request.method !== 'GET') return;
  const url = new URL(event.request.url);
  // Only handle same-origin GET requests
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    caches.match(event.request).then((cached) => {
      if (cached) return cached;
      return fetch(event.request).then((response) => {
        // Cache successful responses for future offline use
        if (response.ok && response.type === 'basic') {
          const clone = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, clone)).catch(() => {});
        }
        return response;
      }).catch(() => {
        // Offline fallback — try to serve cached page for navigation requests
        if (event.request.mode === 'navigate') {
          return caches.match('/epoxy-estimate');
        }
      });
    })
  );
});
